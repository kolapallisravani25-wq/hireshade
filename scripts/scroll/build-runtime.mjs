#!/usr/bin/env node
/**
 * Bundles the framework-free auto-scroll DOM adapter into a classic IIFE so a
 * plain HTML surface (the Electron demo overlay) can use it over file:// — ES
 * modules are blocked by CORS there.
 *
 * Output (committed): artifacts/craft-vita/src/overlay/autoscroll/overlay-autoscroll.iife.js
 * Usage: node scripts/scroll/build-runtime.mjs
 */
import { createRequire } from "node:module";
import { existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const entry = path.join(root, "artifacts", "craft-vita", "src", "overlay", "autoscroll", "index.ts");
const outfile = path.join(root, "artifacts", "craft-vita", "src", "overlay", "autoscroll", "overlay-autoscroll.iife.js");

function findEsbuild() {
  const candidates = [
    path.join(root, "artifacts", "api-server", "node_modules", "esbuild", "lib", "main.js"),
    path.join(root, "artifacts", "craft-vita", "node_modules", "esbuild", "lib", "main.js"),
  ];
  for (const candidate of candidates) if (existsSync(candidate)) return candidate;
  const store = path.join(root, "node_modules", ".pnpm");
  if (existsSync(store)) {
    for (const dir of readdirSync(store)) {
      if (!dir.startsWith("esbuild@")) continue;
      const candidate = path.join(store, dir, "node_modules", "esbuild", "lib", "main.js");
      if (existsSync(candidate)) return candidate;
    }
  }
  throw new Error("esbuild not found (run pnpm install)");
}

const { buildSync } = require(findEsbuild());
mkdirSync(path.dirname(outfile), { recursive: true });
buildSync({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "iife",
  globalName: "HireShadeAutoScroll",
  target: ["chrome120"],
  legalComments: "none",
  banner: {
    js: "/* GENERATED by scripts/scroll/build-runtime.mjs — do not edit by hand. Source: src/overlay/autoscroll/*.ts */",
  },
});

const banner = readFileSync(outfile, "utf8").split("\n").slice(0, 2).join("\n");
console.log(JSON.stringify({
  outfile: path.relative(root, outfile).replace(/\\/g, "/"),
  bytes: statSync(outfile).size,
  banner,
}, null, 2));
