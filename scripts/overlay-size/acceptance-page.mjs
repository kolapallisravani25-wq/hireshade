/**
 * O3 — generates the standalone acceptance surface used by the Electron/CDP
 * harness. It reuses the real demo overlay stylesheet (so O1's token changes in
 * artifacts/craft-vita/src/demo/overlay.html flow through) and layers the
 * preset geometry / readability contract on top.
 */
import { readFileSync } from "node:fs";
import { DEFAULT_PRESET_ID, READABILITY_FLOORS } from "./presets-contract.mjs";

function extractStyle(html) {
  const match = html.match(/<style>([\s\S]*?)<\/style>/i);
  if (!match) throw new Error("demo overlay.html has no <style> block to reuse");
  return match[1];
}

export function buildAcceptanceHtml({ overlayHtmlPath, presets, presetSource, title, floors }) {
  const overlayHtml = readFileSync(overlayHtmlPath, "utf8");
  const baseStyle = extractStyle(overlayHtml);
  const presetCss = presets
    .map(function (preset) {
      return [
        '#size-card[data-preset="' + preset.id + '"] {',
        "  width: " + preset.widthPx + "px;",
        "  height: " + preset.heightPx + "px;",
        "  --scrim: " + preset.scrim + ";",
        "  --answer-font-size: " + preset.fontCssPx + "px;",
        "  --answer-line-height: " + preset.lineHeight + ";",
        "  --answer-max-ch: " + preset.maxCh + ";",
        "}",
      ].join("\n");
    })
    .join("\n");

  const presetsJson = JSON.stringify(presets);
  const floorsJson = JSON.stringify(floors ?? READABILITY_FLOORS);
  const page = [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '  <meta charset="utf-8" />',
    "  <title>" + (title || "HireShade overlay size acceptance") + "</title>",
    "  <style>",
    baseStyle,
    "  </style>",
    "  <style>",
    "    html, body { height: 100%; margin: 0; overflow: hidden; background: #6b7280; }",
    "    #desktop-backdrop { position: fixed; inset: 0; background: var(--desktop-backdrop, #6b7280); z-index: 0; }",
    "    #size-card {",
    "      position: absolute; left: 50%; top: 50%; transform: translate(-50%, -50%);",
    "      box-sizing: border-box; padding: 16px 18px; overflow: hidden;",
    "      background: var(--scrim, rgba(8,10,16,0.8)); color: #f4f7ff;",
    "      border: 1px solid rgba(255,255,255,0.14); border-radius: 16px;",
    "      box-shadow: 0 24px 70px rgba(0,0,0,0.5); z-index: 2;",
    "      font-family: 'Segoe UI', Inter, system-ui, sans-serif;",
    "    }",
    "    #size-card .size-head { display: flex; align-items: center; gap: 8px; margin-bottom: 10px; }",
    "    #size-card .size-brand { font-weight: 700; font-size: 13px; letter-spacing: 0.2px; }",
    "    #size-card .size-preset-label { font-size: 10px; letter-spacing: 0.12em; text-transform: uppercase; opacity: 0.75; }",
    "    #answer-viewport { position: relative; overflow: hidden; }",
    "    #answer-content { will-change: transform; }",
    "    #answer-text {",
    "      font-size: var(--answer-font-size); line-height: var(--answer-line-height);",
    "      color: #f4f7ff; max-width: calc(var(--answer-max-ch) * 1ch);",
    "      overflow-wrap: break-word; word-break: normal; text-overflow: clip;",
    "      white-space: normal;",
    "    }",
    "    #answer-text .answer-bullets { margin: 8px 0 0 18px; padding: 0; }",
    "    #answer-text .answer-bullets li { margin-bottom: 4px; }",
    "    #answer-text .answer-heading { font-size: 11px; letter-spacing: 0.12em; text-transform: uppercase; opacity: 0.7; margin-bottom: 6px; }",
    "    #answer-text code { font-family: Consolas, monospace; }",
    "    #size-card[data-preset] { }",
    presetCss,
    "  </style>",
    "</head>",
    "<body>",
    '  <div id="desktop-backdrop"></div>',
    '  <div id="size-card" data-preset="' + DEFAULT_PRESET_ID + '">',
    '    <div class="size-head"><span class="size-brand">HireShade</span><span class="size-preset-label" id="preset-label"></span></div>',
    '    <div id="answer-viewport"><div id="answer-content"><div id="answer-text" data-testid="answer-text"></div></div></div>',
    "  </div>",
    "<script>",
    "window.__SIZE_PRESETS__ = " + presetsJson + ";",
    "window.__SIZE_FLOORS__ = " + floorsJson + ";",
    "window.__SIZE_PRESET_SOURCE__ = " + JSON.stringify(presetSource) + ";",
    "window.__SIZE_STORAGE_KEY__ = 'hireshade.overlay.preset.v1:size-demo';",
    "window.__SIZE_DEFAULT_PRESET__ = " + JSON.stringify(DEFAULT_PRESET_ID) + ";",
    "window.__bgClicks = 0;",
    "window.__overlayClicks = 0;",
    "(function () {",
    "  'use strict';",
    "  var PRESETS = window.__SIZE_PRESETS__;",
    "  var FLOORS = window.__SIZE_FLOORS__;",
    "  var STORAGE_KEY = window.__SIZE_STORAGE_KEY__;",
    "  var DEFAULT_PRESET = window.__SIZE_DEFAULT_PRESET__;",
    "  var card = document.getElementById('size-card');",
    "  var answerText = document.getElementById('answer-text');",
    "  var answerViewport = document.getElementById('answer-viewport');",
    "  var answerContent = document.getElementById('answer-content');",
    "  var presetLabel = document.getElementById('preset-label');",
    "  var state = { preset: null, fitFontPx: null, storedOnBoot: null };",
    "  function presetInfo(id) { for (var i = 0; i < PRESETS.length; i++) if (PRESETS[i].id === id) return PRESETS[i]; return null; }",
    "  function countWords(text) { var value = String(text || '').trim(); return value ? value.split(/\\s+/).filter(Boolean).length : 0; }",
    "  function detectTokens(text) {",
    "    var source = String(text || ''); var tokens = [];",
    "    if (/\\*\\*[^*]+\\*\\*/.test(source)) tokens.push('**bold**');",
    "    if (/^#{1,6}\\s/m.test(source)) tokens.push('# heading');",
    "    if (source.indexOf(String.fromCharCode(96)) !== -1) tokens.push('backtick code');",
    "    if (/^\\s*[-*+]\\s/m.test(source)) tokens.push('- bullet marker');",
    "    if (/\\[[^\\]]*\\]\\([^)]*\\)/.test(source)) tokens.push('[link](url)');",
    "    return tokens;",
    "  }",
    "  function applyPreset(id) {",
    "    var preset = presetInfo(id); if (!preset) throw new Error('unknown preset ' + id);",
    "    var t0 = performance.now();",
    "    card.setAttribute('data-preset', id);",
    "    // Preset change must reset any inline auto-fit font override so the",
    "    // preset's own typography applies immediately (one-frame re-layout).",
    "    answerText.style.fontSize = '';",
    "    presetLabel.textContent = preset.label || id;",
    "    // Size the answer viewport from the ACTUAL card box (O1 geometry may be",
    "    // small at 1280x800); never let the viewport overflow the card.",
    "    var head = card.querySelector('.size-head');",
    "    var available = card.clientHeight - (head ? head.offsetHeight : 0) - 32;",
    "    answerViewport.style.height = Math.max(60, Math.round(available)) + 'px';",
    "    void card.offsetHeight;",
    "    void answerText.offsetHeight;",
    "    var t1 = performance.now();",
    "    state.preset = id;",
    "    try { localStorage.setItem(STORAGE_KEY, JSON.stringify({ preset: id, updatedAt: Date.now() })); } catch (error) {}",
    "    return { id: id, applyMs: t1 - t0 };",
    "  }",
    "  function storedPreset() {",
    "    try { var raw = localStorage.getItem(STORAGE_KEY); if (!raw) return null; var parsed = JSON.parse(raw); return parsed && parsed.preset ? parsed.preset : null; } catch (error) { return null; }",
    "  }",
    "  function bootPreset() {",
    "    state.storedOnBoot = storedPreset();",
    "    var id = state.storedOnBoot && presetInfo(state.storedOnBoot) ? state.storedOnBoot : DEFAULT_PRESET;",
    "    return applyPreset(id);",
    "  }",
    "  function setBackdrop(color) { document.documentElement.style.setProperty('--desktop-backdrop', color); return color; }",
    "  function autoFit() {",
    "    var preset = presetInfo(state.preset); var base = preset ? preset.fontCssPx : 16;",
    "    var size = base; answerText.style.fontSize = size + 'px'; var guard = 0;",
    "    while (guard++ < 80) {",
    "      var fitsWidth = answerText.scrollWidth <= answerViewport.clientWidth + 1;",
    "      var fitsHeight = answerText.scrollHeight <= answerViewport.clientHeight + 1;",
    "      if (fitsWidth && fitsHeight) break;",
    "      if (size <= FLOORS.minFontCssPx) break;",
    "      size = Math.max(FLOORS.minFontCssPx, size - 0.5);",
    "      answerText.style.fontSize = size + 'px';",
    "    }",
    "    state.fitFontPx = size;",
    "    return { fontSize: size, iterations: guard, fitsWidth: answerText.scrollWidth <= answerViewport.clientWidth + 1, fitsHeight: answerText.scrollHeight <= answerViewport.clientHeight + 1 };",
    "  }",
    "  function inline(text) {",
    "    var escaped = String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');",
    "    escaped = escaped.replace(/\\*\\*([^*]+)\\*\\*/g, '<strong>$1</strong>');",
    "    var bt = String.fromCharCode(96);",
    "    var re = new RegExp(bt + '([^' + bt + ']+)' + bt, 'g');",
    "    escaped = escaped.replace(re, '<code>$1</code>');",
    "    return escaped;",
    "  }",
    "  function renderMarkdown(markdown) {",
    "    var lines = String(markdown).split('\\n'); var out = []; var inList = false; var hookRendered = false;",
    "    for (var i = 0; i < lines.length; i++) {",
    "      var line = lines[i];",
    "      var bullet = line.match(/^\\s*[-*+]\\s+(.*)$/);",
    "      if (bullet) { if (!inList) { out.push('<ul class=\"answer-bullets\">'); inList = true; } out.push('<li>' + inline(bullet[1]) + '</li>'); continue; }",
    "      if (inList) { out.push('</ul>'); inList = false; }",
    "      var heading = line.match(/^#{1,6}\\s+(.*)$/);",
    "      if (heading) { out.push('<div class=\"answer-heading\">' + inline(heading[1]) + '</div>'); continue; }",
    "      if (!line.trim()) continue;",
    "      if (!hookRendered) { out.push('<div class=\"answer-hook\" data-testid=\"answer-hook\">' + inline(line) + '</div>'); hookRendered = true; }",
    "      else out.push('<div class=\"answer-paragraph\">' + inline(line) + '</div>');",
    "    }",
    "    if (inList) out.push('</ul>');",
    "    answerText.innerHTML = out.join('');",
    "    return autoFit();",
    "  }",
    "  function setAnswer(text) { answerText.textContent = String(text); return autoFit(); }",
    "  function setAnswerMarkdown(markdown) { return renderMarkdown(markdown); }",
    "  function parseColor(input) {",
    "    var match = String(input || '').match(/rgba?\\(([^)]+)\\)/);",
    "    if (!match) return null;",
    "    var parts = match[1].split(',').map(function (value) { return parseFloat(value.trim()); });",
    "    return { r: parts[0], g: parts[1], b: parts[2], a: parts.length > 3 ? parts[3] : 1 };",
    "  }",
    "  function hexToRgb(hex) {",
    "    var value = String(hex || '#ffffff').replace('#', '');",
    "    if (value.length === 3) value = value[0] + value[0] + value[1] + value[1] + value[2] + value[2];",
    "    return { r: parseInt(value.slice(0, 2), 16), g: parseInt(value.slice(2, 4), 16), b: parseInt(value.slice(4, 6), 16), a: 1 };",
    "  }",
    "  function composite(foreground, background) {",
    "    var alpha = foreground.a + background.a * (1 - foreground.a);",
    "    if (alpha === 0) return { r: 0, g: 0, b: 0, a: 1 };",
    "    return {",
    "      r: (foreground.r * foreground.a + background.r * background.a * (1 - foreground.a)) / alpha,",
    "      g: (foreground.g * foreground.a + background.g * background.a * (1 - foreground.a)) / alpha,",
    "      b: (foreground.b * foreground.a + background.b * background.a * (1 - foreground.a)) / alpha,",
    "      a: 1,",
    "    };",
    "  }",
    "  function channel(value) { var c = value / 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); }",
    "  function luminosity(color) { return 0.2126 * channel(color.r) + 0.7152 * channel(color.g) + 0.0722 * channel(color.b); }",
    "  function contrastRatio(a, b) { var la = luminosity(a); var lb = luminosity(b); var hi = Math.max(la, lb); var lo = Math.min(la, lb); return (hi + 0.05) / (lo + 0.05); }",
    "  function measureCh(fontSize, family, weight, style) {",
    "    if (!measureCh.canvas) measureCh.canvas = document.createElement('canvas');",
    "    var ctx = measureCh.canvas.getContext('2d');",
    "    ctx.font = (style || 'normal') + ' ' + (weight || '400') + ' ' + fontSize + 'px ' + family;",
    "    var width = ctx.measureText('0000000000').width / 10;",
    "    return width > 0 ? width : fontSize * 0.5;",
    "  }",
    "  function countVisibleWords(root, viewportRect) {",
    "    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);",
    "    var visible = 0; var node;",
    "    while ((node = walker.nextNode())) {",
    "      var text = node.nodeValue || ''; var regex = /\\S+/g; var match;",
    "      while ((match = regex.exec(text))) {",
    "        var range = document.createRange();",
    "        range.setStart(node, match.index); range.setEnd(node, match.index + match[0].length);",
    "        var rect = range.getBoundingClientRect();",
    "        if (rect.height === 0) continue;",
    "        if (rect.top < viewportRect.bottom && rect.bottom > viewportRect.top) visible++;",
    "      }",
    "    }",
    "    return visible;",
    "  }",
    "  function getMetrics(backdropHex) {",
    "    var cs = getComputedStyle(answerText);",
    "    var cardCs = getComputedStyle(card);",
    "    var fontSize = parseFloat(cs.fontSize);",
    "    var lineHeightPx = parseFloat(cs.lineHeight);",
    "    var ch = measureCh(fontSize, cs.fontFamily, cs.fontWeight, cs.fontStyle);",
    "    var textColor = parseColor(cs.color);",
    "    var scrim = parseColor(cardCs.backgroundColor);",
    "    var backdrop = hexToRgb(backdropHex || '#ffffff');",
    "    var composited = scrim && scrim.a < 1 ? composite(scrim, backdrop) : (scrim || backdrop);",
    "    var viewportRect = answerViewport.getBoundingClientRect();",
    "    var maxWidthPx = cs.maxWidth && cs.maxWidth !== 'none' ? parseFloat(cs.maxWidth) : answerText.clientWidth;",
    "    var hook = answerText.querySelector('[data-testid=\"answer-hook\"]');",
    "    var docScrollWidth = document.scrollingElement ? document.scrollingElement.scrollWidth : document.documentElement.scrollWidth;",
    "    return {",
    "      preset: state.preset, presetSource: window.__SIZE_PRESET_SOURCE__, dpr: window.devicePixelRatio,",
    "      fontSizeCssPx: fontSize, lineHeightPx: lineHeightPx, lineHeightRatio: fontSize > 0 ? lineHeightPx / fontSize : 0,",
    "      maxWidthPx: maxWidthPx, maxLineChCss: ch > 0 ? maxWidthPx / ch : 0, longestLineCh: ch > 0 ? answerText.clientWidth / ch : 0,",
    "      contrast: { ratio: textColor ? contrastRatio(textColor, composited) : 0, backdrop: backdropHex || '#ffffff', textColor: cs.color, scrim: cardCs.backgroundColor },",
    "      layout: {",
    "        answerClientWidth: answerText.clientWidth, answerScrollWidth: answerText.scrollWidth,",
    "        answerClientHeight: answerText.clientHeight, answerScrollHeight: answerText.scrollHeight,",
    "        viewportClientHeight: answerViewport.clientHeight, contentHeight: answerContent.getBoundingClientRect().height,",
    "        docScrollWidth: docScrollWidth, innerWidth: window.innerWidth, textOverflow: cs.textOverflow,",
    "        overflowWrap: cs.overflowWrap, wordBreak: cs.wordBreak, webkitLineClamp: cs.webkitLineClamp || 'none', whiteSpace: cs.whiteSpace,",
    "      },",
    "      text: { chars: answerText.textContent.length, words: countWords(answerText.textContent) },",
    "      speakability: {",
    "        hookWords: hook ? countWords(hook.textContent) : null,",
    "        firstBulletWords: (function () { var li = answerText.querySelector('li'); return li ? countWords(li.textContent) : 0; })(),",
    "        firstScreenfulWords: (hook ? countWords(hook.textContent) : 0) + (function () { var li = answerText.querySelector('li'); return li ? countWords(li.textContent) : 0; })(),",
    "        viewportVisibleWords: countVisibleWords(answerText, viewportRect),",
    "        bulletCount: answerText.querySelectorAll('li').length,",
    "        markdownTokens: detectTokens(answerText.textContent),",
    "      },",
    "      fitFontPx: state.fitFontPx,",
    "      clicks: { overlay: window.__overlayClicks, background: window.__bgClicks },",
    "    };",
    "  }",
    "  function relayoutTo(id) {",
    "    return new Promise(function (resolve) {",
    "      var t0 = performance.now();",
    "      var applied = applyPreset(id);",
    "      requestAnimationFrame(function () {",
    "        var t1 = performance.now();",
    "        resolve({ id: id, applyMs: applied.applyMs, frameMs: t1 - t0, preset: state.preset, fontSize: parseFloat(getComputedStyle(answerText).fontSize) });",
    "      });",
    "    });",
    "  }",
    "  document.addEventListener('click', function () { window.__overlayClicks += 1; });",
    "  window.__sizeHarness = {",
    "    constants: FLOORS, presets: PRESETS, presetSource: window.__SIZE_PRESET_SOURCE__,",
    "    bootPreset: bootPreset, applyPreset: applyPreset, relayoutTo: relayoutTo, getPreset: function () { return state.preset; },",
    "    getStoredPreset: storedPreset, setBackdrop: setBackdrop, setAnswer: setAnswer, setAnswerMarkdown: setAnswerMarkdown,",
    "    autoFit: autoFit, getMetrics: getMetrics, getClicks: function () { return { overlay: window.__overlayClicks, background: window.__bgClicks }; },",
    "    resetClicks: function () { window.__overlayClicks = 0; window.__bgClicks = 0; },",
    "    getFitFontPx: function () { return state.fitFontPx; },",
    "    getStoredRaw: function () { try { return localStorage.getItem(STORAGE_KEY); } catch (error) { return null; } },",
    "  };",
    "  // A reopened overlay restores its persisted preset before first paint.",
    "  bootPreset();",
    "  window.__sizeReady = true;",
    "})();",
    "</script>",
    "</body>",
    "</html>",
  ].join("\n");
  return page;
}

export function buildBackgroundHtml() {
  return [
    "<!doctype html>",
    '<html lang="en"><head><meta charset="utf-8" /><title>Size acceptance background app</title>',
    "<style>",
    "html,body{height:100%;margin:0;font-family:'Segoe UI',system-ui,sans-serif;background:linear-gradient(135deg,#0f172a,#1e293b);color:#e2e8f0;}",
    "body{display:flex;align-items:center;justify-content:center;}",
    ".panel{text-align:center;}",
    "#bg-clicks{font-size:56px;font-weight:800;color:#7dd3fc;}",
    "p{opacity:.7;max-width:520px;}",
    "</style></head><body>",
    '<div class="panel"><h1>Background application</h1><div id="bg-clicks">0</div><p>OS-level clicks that pass through the overlay land here.</p></div>',
    "<script>",
    "window.__bgClicks = 0;",
    "document.addEventListener('click', function (event) { window.__bgClicks += 1; document.getElementById('bg-clicks').textContent = String(window.__bgClicks); window.__bgLastClick = { x: event.clientX, y: event.clientY, at: Date.now() }; });",
    "window.__bgReady = true;",
    "</script></body></html>",
  ].join("\n");
}
