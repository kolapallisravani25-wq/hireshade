export function normalizeSttTranscript(text: string): string {
  if (!text?.trim()) return text || "";
  let next = text;
  for (const [pattern, replacement] of STT_CORRECTIONS) {
    next = next.replace(pattern, replacement);
  }
  return next.replace(/\s+/g, " ").trim();
}
